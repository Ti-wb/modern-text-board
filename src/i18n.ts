export const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  "zh-TW": zhTW,
  en,
};

export function resolveLocale(
  savedLocale?: unknown,
  browserLocales: readonly string[] =
    typeof navigator === "undefined" ? [] : navigator.languages,
): Locale {
  if (savedLocale === "zh-TW" || savedLocale === "en") return savedLocale;

  for (const candidate of browserLocales) {
    const normalized = candidate.toLowerCase();
    if (normalized === "zh-tw" || normalized.startsWith("zh-hant")) return "zh-TW";
    if (normalized === "en" || normalized.startsWith("en-")) return "en";
  }

  return "zh-TW";
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  params: TranslationParams = {},
): string {
  const template = dictionaries[locale][key] ?? dictionaries["zh-TW"][key];
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

export function t(
  key: TranslationKey,
  locale: Locale = "zh-TW",
  params?: TranslationParams,
): string {
  return translate(locale, key, params);
}

export function getTranslator(locale: Locale) {
  return (key: TranslationKey, params?: TranslationParams) =>
    translate(locale, key, params);
}

export function applyDocumentLocale(locale: Locale): void {
  if (typeof document !== "undefined") document.documentElement.lang = locale;
}
